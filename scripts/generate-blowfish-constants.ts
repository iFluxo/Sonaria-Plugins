/**
 * Generates the canonical Blowfish initialisation tables (P-array + S-boxes)
 * from the hexadecimal expansion of pi and writes them to
 * `packages/src/core/blowfish-constants.ts`.
 *
 * Run with: `bun scripts/generate-blowfish-constants.ts`
 *
 * Blowfish uses the fractional part of pi as its "nothing up my sleeve"
 * constants: P[0..17] followed by S0[0..255], S1, S2 and S3 — 1042 uint32 words
 * or 8336 hexadecimal digits in total.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";

const HEX_DIGITS = 1042 * 8;
const DECIMAL_DIGITS = Math.ceil(HEX_DIGITS * Math.log10(16)) + 60;

/** Integer arctangent: `atan(1/x)` scaled by `10^precision`. */
function atanInv(x: bigint, one: bigint): bigint {
  let sum = 0n;
  let term = one / x;
  let xSquared = x * x;
  for (let k = 0n; term !== 0n; k++) {
    const current = term / (2n * k + 1n);
    sum += k % 2n === 0n ? current : -current;
    term /= xSquared;
  }
  return sum;
}

/** Machin's formula: pi = 16*atan(1/5) - 4*atan(1/239). */
function piFractionHex(digits: number): string {
  const one = 10n ** BigInt(digits);
  const pi = 16n * atanInv(5n, one) - 4n * atanInv(239n, one);
  let fraction = pi - 3n * one;
  let hex = "";
  while (hex.length < digits) {
    fraction *= 16n;
    const digit = Number(fraction / one);
    fraction %= one;
    hex += digit.toString(16);
  }
  return hex;
}

const hex = piFractionHex(DECIMAL_DIGITS).slice(0, HEX_DIGITS);
if (!hex.startsWith("243f6a8885a308d3")) {
  throw new Error("pi expansion does not look right, refusing to write constants");
}

const words = hex.match(/.{8}/gu)?.map((word) => `0x${word}`) ?? [];
if (words.length !== 1042) throw new Error(`expected 1042 words, got ${words.length}`);

const banner = `// Generated by scripts/generate-blowfish-constants.ts — do not edit by hand.
// The hexadecimal digits of pi (P-array + S-boxes), the canonical Blowfish init tables.
`;

const body = `/** 1042 uint32 words: P[0..17] then S0..S3 (4 x 256). */
export const BLOWFISH_INIT = Uint32Array.from([
${chunk(words, 6)
  .map((line) => `  ${line.join(", ")},`)
  .join("\n")}
]);
`;

function chunk<T>(items: T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}

const target = path.join(import.meta.dir, "..", "packages", "src", "core", "blowfish-constants.ts");
await writeFile(target, banner + body, "utf8");
console.log(`wrote ${words.length} words to ${path.relative(process.cwd(), target)}`);
